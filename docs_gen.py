"""Generate docs/data_dictionary.md from dim_indicator so the docs cannot drift
away from the warehouse. Run after the pipeline (CI does this)."""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import ROOT, WAREHOUSE_DIR, get_logger

log = get_logger("docs_gen")

UNITS = {
    "percent": "%", "percent_gdp": "% of GDP", "nad_billion": "N$ billion",
    "nad_million": "N$ million", "usd": "US$", "persons": "persons",
    "celsius": "°C", "mm": "mm", "z_score": "standard deviations",
    "months": "months of imports", "kgoe": "kg oil equivalent",
    "tco2e": "t CO2e per person",
}
DIRECTIONS = {
    "up_good": "higher is better", "up_bad": "higher is worse", "neutral": "context",
}


def main() -> int:
    dim = pd.read_csv(WAREHOUSE_DIR / "dim_indicator.csv")
    fact = pd.read_csv(WAREHOUSE_DIR / "fact_indicator.csv", parse_dates=["date"])

    stats = fact.groupby("indicator").agg(
        n=("value", "size"), first=("date", "min"), last=("date", "max"),
        forecast=("is_forecast", "sum"),
    )
    dim = dim.merge(stats, left_on="indicator", right_index=True, how="left")

    lines = [
        "# Data dictionary",
        "",
        "Generated by `src/docs_gen.py` from `data/warehouse/dim_indicator.csv`. Do not edit by hand.",
        "",
        f"{len(dim)} series across {dim['category'].nunique()} categories.",
        "",
    ]

    for category, grp in dim.groupby("category"):
        lines += [f"## {category}", "",
                  "| Indicator | Label | Unit | Freq | Reading | Obs | Span | Projections | Source |",
                  "|---|---|---|---|---|---|---|---|---|"]
        for _, r in grp.sort_values("indicator").iterrows():
            span = (f"{r['first']:%Y}–{r['last']:%Y}" if pd.notna(r["first"]) else "—")
            lines.append(
                f"| `{r['indicator']}` | {r['label']} | {UNITS.get(r['unit'], r['unit'])} "
                f"| {r['frequency']} | {DIRECTIONS.get(r['direction'], r['direction'])} "
                f"| {int(r['n']) if pd.notna(r['n']) else 0} | {span} "
                f"| {int(r['forecast']) if pd.notna(r['forecast']) else 0} | {r['source']} |"
            )
        lines.append("")

    out = ROOT / "docs" / "data_dictionary.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    log.info("wrote %s (%s series)", out.relative_to(ROOT), len(dim))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
